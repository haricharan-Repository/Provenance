import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { classify } from './triage';
import type { Evidence } from './falsify';
import { ROOT, TL, config, flag, flatten, loadRequirements, openHighRisk, readReport, tableRows, today, write, type RiskBand, type TestRun } from './lib';

type Status = 'VERIFIED' | 'FAILED' | 'BLOCKED' | 'NOT_COVERED';

const pct = (n: number) => `${Math.round(n * 100)}%`;
const ratio = (part: number, whole: number) => (whole ? part / whole : 0);

export function verdict(args: string[]) {
  const c = config();
  const resultsPath = flag(args, 'results') ?? join(ROOT, 'reports', 'results.json');
  if (!existsSync(resultsPath)) throw new Error(`No results at ${resultsPath}. Run the suite first.`);
  const runs = flatten(readReport(resultsPath)).filter((r) => !r.tags.includes('@flaky'));
  const evidencePath = join(TL, 'falsification.json');
  const evidence: Evidence[] = existsSync(evidencePath) ? JSON.parse(readFileSync(evidencePath, 'utf8')).tests : [];
  const byKey = new Map(evidence.map((e) => [e.key, e.verdict]));
  const reqs = loadRequirements();
  const openGate = new Set(openHighRisk(reqs).map((q) => q.REQ));

  const proven = (r: TestRun) => ['PROVEN', 'HOLLOW→FIXED'].includes(byKey.get(r.key) ?? '');

  const matrix = reqs.map((r) => {
    const mine = runs.filter((t) => t.reqs.includes(r.id));
    const failed = mine.filter((t) => t.outcome === 'unexpected' || t.outcome === 'flaky');
    const specs = new Set(mine.map((t) => t.key));
    let status: Status;
    let note = '';
    if (!mine.length) {
      status = 'NOT_COVERED';
      note = r.notCoveredReason || 'No test results and no written reason.';
    } else if (failed.length) {
      status = 'FAILED';
      note = `${failed.length} of ${mine.length} run(s) failed`;
    } else if (openGate.has(r.id)) {
      status = 'BLOCKED';
      note = 'OPEN high-risk clarification';
    } else if (mine.some((t) => t.outcome !== 'expected')) {
      status = 'BLOCKED';
      note = 'Skipped runs';
    } else if (!mine.every(proven)) {
      status = 'BLOCKED';
      note = 'Green but not proven by falsification';
    } else {
      status = 'VERIFIED';
      note = `${specs.size} test(s), ${mine.length} run(s)`;
    }
    return { r, status, note, specs: specs.size };
  });

  const coverage = ratio(
    matrix.filter((m) => m.status === 'VERIFIED').reduce((s, m) => s + m.r.score, 0),
    matrix.reduce((s, m) => s + m.r.score, 0),
  );
  const count = (v: string) => evidence.filter((e) => e.verdict === v).length;
  const provenRate = ratio(count('PROVEN') + count('HOLLOW→FIXED'), evidence.length);
  const stabilityRate = ratio(evidence.length - count('FLAKY'), evidence.length);
  const score = Math.round(50 * coverage + 30 * provenRate + 20 * stabilityRate);

  const failedRuns = runs.filter((r) => r.outcome === 'unexpected');
  const defects = failedRuns.filter((r) => classify(r.error).cls === 'PRODUCT_DEFECT');
  const heals = tableRows(join(TL, 'healing.md'));
  const drift = tableRows(join(TL, 'drift.md'));
  const driftOf = (t: string) => drift.filter((d) => d.Type === t).length;

  const noGo: string[] = [];
  const risks: string[] = [];
  for (const m of matrix) {
    if (m.status === 'VERIFIED') continue;
    const line = `${m.r.id} (${m.r.band} risk) is ${m.status}: ${m.note}`;
    (m.r.band === 'high' ? noGo : risks).push(line);
  }
  if (defects.length) noGo.push(`${defects.length} failing run(s) classified PRODUCT_DEFECT.`);
  if (score < c.verdict.noGoBelowScore) noGo.push(`Truth Score ${score} is below ${c.verdict.noGoBelowScore}.`);
  if (score < c.verdict.goMinScore) risks.push(`Truth Score ${score} is below the GO bar of ${c.verdict.goMinScore}.`);
  if (driftOf('POSSIBLE_DEFECT')) risks.push(`${driftOf('POSSIBLE_DEFECT')} unresolved POSSIBLE_DEFECT drift item(s).`);
  const recommendation = noGo.length ? 'NO-GO' : risks.length ? 'GO WITH RISKS' : 'GO';

  const bandRow = (band: RiskBand) => {
    const inBand = matrix.filter((m) => m.r.band === band);
    const done = inBand.filter((m) => m.status === 'VERIFIED').length;
    return `| ${band} | ${done}/${inBand.length} | ${inBand.length ? pct(done / inBand.length) : 'n/a'} |`;
  };
  const reasons = [...noGo, ...risks];

  write(
    join(TL, 'truth-report.md'),
    `# Truth Report\n\nGenerated by \`tl verdict\` on ${today()} from ${resultsPath.replace(`${ROOT}/`, '')}.\n\n` +
      `## Verdict: ${recommendation}\n\n**Truth Score: ${score}/100** ` +
      `(50 × ${pct(coverage)} risk-weighted coverage + 30 × ${pct(provenRate)} proven + 20 × ${pct(stabilityRate)} stable)\n\n` +
      `${reasons.map((x) => `- ${x}`).join('\n') || '- Every requirement is verified and proven.'}\n\n` +
      `## Traceability\n\n| REQ | Title | Risk | Score | Tests | Status | Note |\n|---|---|---|---|---|---|---|\n` +
      `${matrix.map((m) => `| ${m.r.id} | ${m.r.title} | ${m.r.band} | ${m.r.score} | ${m.specs} | ${m.status} | ${m.note} |`).join('\n')}\n\n` +
      `## Risk coverage\n\n| Risk | Verified | Rate |\n|---|---|---|\n${(['high', 'medium', 'low'] as const).map(bandRow).join('\n')}\n\n` +
      `## Falsification\n\nProven: ${count('PROVEN')}. Hollow fixed: ${count('HOLLOW→FIXED')}. Hollow: ${count('HOLLOW')}. Flaky: ${count('FLAKY')}. Broken: ${count('BROKEN')}.\n\n` +
      `## Healing\n\nHealed: ${heals.filter((h) => h.Action === 'HEALED').length}. Refused: ${heals.filter((h) => h.Action === 'REFUSED').length}. Defects raised: ${defects.length}.\n\n` +
      `## Drift\n\nPossible defects: ${driftOf('POSSIBLE_DEFECT')}. Requirement gaps: ${driftOf('REQUIREMENT_GAP')}.\n`,
  );
  console.log(`${recommendation}  Truth Score ${score}/100`);
  matrix.forEach((m) => console.log(`${m.status.padEnd(12)}${m.r.id} ${m.note}`));
  reasons.forEach((x) => console.log(`- ${x}`));
}
