import { readdirSync } from 'node:fs';
import { join } from 'node:path';
import { REQ_DIR, TL, config, inventory, loadRequirements, openHighRisk, today, write, type RiskBand } from './lib';

const VAGUE =
  /\b(fast|quick(ly)?|user[- ]friendly|appropriate(ly)?|intuitive|seamless(ly)?|robust|easy|easily|simple|reasonable|adequate|as needed|etc\.?|and so on|should work|properly|correctly)\b/gi;

const CHECKS: [string, RegExp, string][] = [
  ['Missing negatives', /\b(invalid|error|reject|refuse|denied|fail|unauthori[sz]ed|unauthenticated|unknown|forbidden|timeout|empty|duplicate|4\d\d)/i, 'No failure path described: invalid input, no permission, timeout, empty state, duplicate submit?'],
  ['Missing boundaries', /\d|\b(min|max|limit|at most|at least|before|after|until)\b/i, 'No numeric or date boundary stated: min/max lengths, limits, dates, currency, locale?'],
  ['Hidden states', /\b(role|admin|guest|anonymous|signed[- ]in|authenticated|logged[- ]in|flag|first[- ]time|returning|concurren)/i, 'No roles or states mentioned: roles, feature flags, first-time vs returning, concurrency?'],
];

export function lint(args: string[]) {
  const reqs = loadRequirements();
  let findings = 0;
  for (const r of reqs) {
    const hits: string[] = [];
    if (!/\bGiven\b[\s\S]*\bwhen\b[\s\S]*\bthen\b/i.test(r.body)) hits.push('Not normalized: no Given/When/Then criteria.');
    const vague = [...new Set(r.body.match(VAGUE)?.map((v) => v.toLowerCase()) ?? [])];
    if (vague.length) hits.push(`Vague terms, demand a measurable value: ${vague.join(', ')}`);
    for (const [name, pattern, hint] of CHECKS) if (!pattern.test(r.body)) hits.push(`${name}: ${hint}`);
    findings += hits.length;
    console.log(`${r.id} ${r.title}: ${hits.length ? '' : 'clean'}`);
    hits.forEach((h) => console.log(`  - ${h}`));
  }
  console.log('Contradictions are not machine-checkable: compare criteria, designs and behaviour by hand.');
  const open = openHighRisk(reqs);
  open.forEach((c) => console.log(`GATE ${c.REQ} ${c.ID} is OPEN on a high-risk requirement: ${c.Question}`));
  console.log(`${findings} finding(s), ${open.length} blocking OPEN question(s).`);
  if (open.length || (args.includes('--strict') && findings)) process.exitCode = 1;
}

export function risk() {
  const reqs = loadRequirements().sort((a, b) => b.score - a.score);
  const c = config();
  const depth: Record<RiskBand, string> = {
    high: 'E2E happy + negatives + boundaries + API contract + cross-browser',
    medium: 'E2E happy + key negatives + API checks',
    low: 'API or single E2E smoke',
  };
  const rows = reqs.map(
    (r) => `| ${r.id} | ${r.title} | ${r.impact} | ${r.likelihood} | ${r.changeFrequency} | ${r.score} | ${r.band} | ${depth[r.band]} |`,
  );
  write(
    join(TL, 'risk-model.md'),
    `# Risk Model\n\nGenerated by \`tl risk\` on ${today()}. Score = Impact × Likelihood × Change Frequency. ` +
      `High ≥ ${c.riskBands.high}, Medium ≥ ${c.riskBands.medium}, otherwise Low.\n\n` +
      `| REQ | Title | Impact | Likelihood | Change | Score | Risk | Required depth |\n|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`,
  );
  console.log(rows.join('\n') || 'No requirements yet.');
}

export function newReq(args: string[]) {
  const title = args.find((a) => !a.startsWith('--'));
  if (!title) throw new Error('Usage: tl new-req "<title>" [--incident]');
  const ids = readdirSync(REQ_DIR).flatMap((f) => /^REQ-(\d+)\.md$/.exec(f)?.[1] ?? []).map(Number);
  const id = `REQ-${String(Math.max(0, ...ids) + 1).padStart(3, '0')}`;
  const origin = args.includes('--incident') ? 'incident' : 'story';
  write(
    join(REQ_DIR, `${id}.md`),
    `---\nid: ${id}\ntitle: ${title}\nsource: ${origin}\nimpact: 3\nlikelihood: 3\nchange_frequency: 2\nnot_covered_reason:\n---\n\n` +
      `## Story\n\nTODO: paste the raw story or incident summary. The default risk scores are placeholders.\n\n` +
      `## Acceptance criteria\n\n- AC1: Given TODO, when TODO, then TODO.\n`,
  );
  console.log(`Created truthline/requirements/${id}.md`);
}

const requiredTags: Record<RiskBand, string[]> = {
  high: ['@ui', '@api', '@negative', '@boundary'],
  medium: ['@ui', '@api', '@negative'],
  low: [],
};

export function trace() {
  const reqs = loadRequirements();
  const known = new Set(reqs.map((r) => r.id));
  const tests = inventory().filter((t) => !t.tags.includes('@flaky'));
  const problems: string[] = [];

  for (const key of new Set(tests.filter((t) => !t.reqs.length).map((t) => t.key))) problems.push(`ORPHAN test, no @REQ tag: ${key}`);
  for (const t of tests) {
    for (const id of t.reqs) if (!known.has(id)) problems.push(`UNKNOWN requirement ${id} in: ${t.key}`);
  }

  console.log('REQ | risk | tests | projects');
  for (const r of reqs) {
    const mine = tests.filter((t) => t.reqs.includes(r.id));
    const specs = new Set(mine.map((t) => t.key));
    const projects = new Set(mine.map((t) => t.project));
    console.log(`${r.id} | ${r.band} (${r.score}) | ${specs.size} | ${[...projects].join(', ') || '-'}`);
    if (!mine.length) {
      if (!r.notCoveredReason) problems.push(`UNCOVERED ${r.id} has no tests and no not_covered_reason`);
      continue;
    }
    const tags = new Set(mine.flatMap((t) => t.tags));
    for (const tag of requiredTags[r.band]) {
      if (!tags.has(tag)) problems.push(`DEPTH ${r.id} (${r.band}) has no ${tag} test`);
    }
    const riskTag = `@risk-${r.band}`;
    if (mine.some((t) => !t.tags.includes(riskTag))) problems.push(`RISK TAG ${r.id} tests must carry ${riskTag}`);
    if (r.band === 'high' && !(projects.has('firefox') && projects.has('webkit'))) {
      problems.push(`DEPTH ${r.id} (high) does not run cross-browser`);
    }
  }
  problems.forEach((p) => console.log(p));
  console.log(`${problems.length} traceability problem(s).`);
  if (problems.length) process.exitCode = 1;
}
